begin;
create schema if not exists aula_privada;
revoke all on schema aula_privada from public, anon, authenticated;
set local search_path = aula_privada, pg_catalog;

create table if not exists users (
  id integer generated by default as identity primary key,
  name text not null, email text not null unique, password text not null,
  role text not null check (role in ('admin', 'teacher', 'student'))
);
create table if not exists sessions (
  token text primary key, uid integer not null references users(id), expiry bigint not null
);
create table if not exists courses (
  id integer generated by default as identity primary key,
  owner integer not null references users(id), title text not null, description text not null,
  category text not null, published integer not null default 0 check (published in (0,1)),
  program text not null default ''
);
create table if not exists lessons (
  id integer generated by default as identity primary key,
  course integer not null references courses(id), title text not null, content text not null,
  file text not null default '', bytes bytea
);
create table if not exists quizzes (
  id integer generated by default as identity primary key,
  course integer not null references courses(id), questions text not null
);
create table if not exists enrollments (
  uid integer references users(id), course integer references courses(id), primary key (uid, course)
);
create table if not exists progress (
  uid integer references users(id), lesson integer references lessons(id), primary key (uid, lesson)
);
create table if not exists passes (
  uid integer references users(id), quiz integer references quizzes(id), primary key (uid, quiz)
);
create table if not exists certificates (
  code text primary key, uid integer not null references users(id), course integer not null references courses(id),
  name text not null, title text not null, issued text not null, expires text not null, unique (uid, course)
);
create index if not exists sessions_expiry_idx on sessions(expiry);
create index if not exists courses_owner_idx on courses(owner);
create index if not exists lessons_course_idx on lessons(course, id);
create index if not exists quizzes_course_idx on quizzes(course, id);
revoke all on all tables in schema aula_privada from public, anon, authenticated;
revoke all on all sequences in schema aula_privada from public, anon, authenticated;
commit;
